"""PR comment bot for the CI/CD evaluation pipeline.

After a pipeline run this module renders the evaluation outcome -- scores,
regressions, and compliance status -- into a Markdown summary and posts it as
a comment on the originating pull request via the GitHub REST API. Posting uses
only the standard library (``urllib``) so the pipeline has no extra runtime
dependency, and the formatting function is fully decoupled from the network so
it can be unit-tested without touching GitHub.
"""

from __future__ import annotations

import json
import urllib.error
import urllib.request
from typing import List, Optional

from src.core.models import ComplianceReport, EvalResult, Severity
from src.pipeline.regression import RegressionReport


# Map of severity -> Markdown badge so the table reads at a glance.
_SEVERITY_EMOJI = {
    Severity.INFO: ":white_check_mark:",
    Severity.LOW: ":large_blue_circle:",
    Severity.MEDIUM: ":yellow_circle:",
    Severity.HIGH: ":orange_circle:",
    Severity.CRITICAL: ":red_circle:",
}


def _scores_table(eval_results: List[EvalResult]) -> str:
    """Render the per-dimension score table as a Markdown string.

    Args:
        eval_results: The evaluation results to tabulate.

    Returns:
        A Markdown table with Dimension / Score / Severity columns.
    """
    if not eval_results:
        return "_No evaluation results for this run._"
    lines = [
        "| Dimension | Score | Severity |",
        "|---|---|---|",
    ]
    for result in sorted(eval_results, key=lambda r: r.dimension):
        emoji = _SEVERITY_EMOJI.get(result.severity, "")
        lines.append(
            f"| {result.dimension} | {result.score:.3f} | {emoji} {result.severity.value} |"
        )
    return "\n".join(lines)


def _regression_section(report: Optional[RegressionReport]) -> str:
    """Render the regression summary as a Markdown section.

    Args:
        report: The regression report, or ``None`` when no comparison ran.

    Returns:
        A Markdown block describing regressions (or their absence).
    """
    if report is None:
        return "_Regression comparison was not run for this build._"
    if not report.findings:
        return "_No dimensions were compared._"
    if not report.has_regression:
        return ":white_check_mark: **No regressions detected** vs. previous run."

    lines = ["**Regressions vs. previous run:**", "", "| Dimension | Previous | Current | Δ | Critical |", "|---|---|---|---|---|"]
    for finding in report.findings:
        if not finding.is_regression:
            continue
        flag = ":rotating_light: yes" if finding.is_critical else "no"
        lines.append(
            f"| {finding.dimension} | {finding.previous_score:.3f} | "
            f"{finding.current_score:.3f} | {finding.delta:+.3f} | {flag} |"
        )
    return "\n".join(lines)


def _compliance_section(report: Optional[ComplianceReport]) -> str:
    """Render the compliance status as a Markdown section.

    Args:
        report: The compliance report, or ``None`` when not generated.

    Returns:
        A Markdown block describing the overall risk tier and finding counts.
    """
    if report is None:
        return "_Compliance report was not generated for this build._"
    n_critical = sum(1 for f in report.findings if f.severity == Severity.CRITICAL)
    return (
        f"**Overall risk tier:** `{report.overall_risk_tier.value}`  \n"
        f"**Findings:** {len(report.findings)} "
        f"(critical: {n_critical})  \n"
        f"**Gaps / recommendations:** {len(report.gaps)}"
    )


def format_eval_markdown(
    model_name: str,
    eval_results: List[EvalResult],
    regression_report: Optional[RegressionReport] = None,
    compliance_report: Optional[ComplianceReport] = None,
) -> str:
    """Build the full Markdown summary posted to a pull request.

    Args:
        model_name: The model that was evaluated.
        eval_results: The evaluation results for this run.
        regression_report: Optional regression comparison.
        compliance_report: Optional compliance report.

    Returns:
        A Markdown document with scores, regressions, and compliance status.
    """
    sections = [
        f"## :shield: AI Risk Evaluation — `{model_name}`",
        "",
        "### Scores",
        _scores_table(eval_results),
        "",
        "### Regressions",
        _regression_section(regression_report),
        "",
        "### Compliance Status",
        _compliance_section(compliance_report),
        "",
        "---\n",
        "_Generated by the AI Risk Evaluation Workbench CI pipeline._",
    ]
    return "\n".join(sections)


def post_pr_comment(
    body: str,
    *,
    token: str,
    repo: str,
    pr_number: int,
    api_url: str = "https://api.github.com",
) -> int:
    """Post a Markdown comment to a pull request via the GitHub REST API.

    Args:
        body: The Markdown body of the comment.
        token: A GitHub personal access / app token (never hardcoded; passed in).
        repo: Target repository in ``owner/name`` form.
        pr_number: The pull request / issue number to comment on.
        api_url: Base URL for the GitHub API (override for enterprise hosts).

    Returns:
        The HTTP status code returned by GitHub.

    Raises:
        ValueError: If ``token`` is empty.
        urllib.error.URLError: On network / API failure.
    """
    if not token:
        raise ValueError("A non-empty GitHub token is required to post a comment.")
    url = f"{api_url.rstrip('/')}/repos/{repo}/issues/{pr_number}/comments"
    payload = json.dumps({"body": body}).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=payload,
        headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=30) as response:  # noqa: S310
        return response.status


def post_pr_comment_from_results(
    model_name: str,
    eval_results: List[EvalResult],
    regression_report: Optional[RegressionReport] = None,
    compliance_report: Optional[ComplianceReport] = None,
    *,
    token: str,
    repo: str,
    pr_number: int,
    api_url: str = "https://api.github.com",
) -> int:
    """Format and post a PR comment in one call.

    Args:
        model_name: The model that was evaluated.
        eval_results: The evaluation results for this run.
        regression_report: Optional regression comparison.
        compliance_report: Optional compliance report.
        token: A GitHub token (never hardcoded; passed in).
        repo: Target repository in ``owner/name`` form.
        pr_number: The pull request / issue number to comment on.
        api_url: Base URL for the GitHub API (override for enterprise hosts).

    Returns:
        The HTTP status code returned by GitHub.
    """
    body = format_eval_markdown(
        model_name,
        eval_results,
        regression_report=regression_report,
        compliance_report=compliance_report,
    )
    return post_pr_comment(
        body,
        token=token,
        repo=repo,
        pr_number=pr_number,
        api_url=api_url,
    )


__all__ = [
    "format_eval_markdown",
    "post_pr_comment",
    "post_pr_comment_from_results",
]
